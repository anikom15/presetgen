import os
import sys
import argparse
import json
import re
import shutil
import hashlib
import tempfile
import time
from data import Preset, Pipeline, Params


MENU_BASE_SHADER = 'menu-base.slang'
MENU_MANIFEST_FILENAME = 'menu-manifest.json'
INCLUDE_PATTERN = re.compile(r'^\s*#include\s+"([^"]+)"')
MENU_NAME_TOKEN_PATTERN = re.compile(r'[^a-z0-9]+')
LOCK_WAIT_SECONDS = 60.0
LOCK_POLL_SECONDS = 0.05


def wrap_comment(text, width=72):
    import textwrap
    return ['# ' + line for line in textwrap.wrap(text, width)]


def load_global_config(config_path):
    config_path = os.path.normpath(config_path)
    if not os.path.exists(config_path):
        raise ValueError(f"Missing required config file: {config_path}")
    with open(config_path, 'r', encoding='utf-8') as f:
        config = json.load(f)
    required = ('root_path', 'pipeline_root', 'parameter_root')
    for key in required:
        value = config.get(key)
        if not isinstance(value, str) or not value.strip():
            raise ValueError(f"Global config '{key}' must be a non-empty string in {config_path}")
    config_dir = os.path.dirname(config_path)
    return {
        'root_path': config['root_path'],
        'shader_root_abs': os.path.normpath(os.path.join(config_dir, config['root_path'])),
        'pipeline_root_abs': os.path.normpath(os.path.join(config_dir, config['pipeline_root'])),
        'parameter_root_abs': os.path.normpath(os.path.join(config_dir, config['parameter_root'])),
    }


def ensure_shader_file_extension(shader_path, shader_ext):
    return shader_path if shader_path.lower().endswith(shader_ext.lower()) else shader_path + shader_ext


class ExclusiveFileLock:
    def __init__(self, lock_path, timeout_seconds=LOCK_WAIT_SECONDS):
        self.lock_path = lock_path
        self.timeout_seconds = timeout_seconds
        self.fd = None

    def __enter__(self):
        os.makedirs(os.path.dirname(self.lock_path), exist_ok=True)
        deadline = time.time() + self.timeout_seconds
        while True:
            try:
                self.fd = os.open(self.lock_path, os.O_CREAT | os.O_EXCL | os.O_WRONLY)
                os.write(self.fd, f"pid={os.getpid()}\n".encode('utf-8'))
                return self
            except FileExistsError:
                if time.time() >= deadline:
                    raise TimeoutError(f"Timed out waiting for lock: {self.lock_path}")
                time.sleep(LOCK_POLL_SECONDS)

    def __exit__(self, exc_type, exc, tb):
        if self.fd is not None:
            os.close(self.fd)
            self.fd = None
        if os.path.exists(self.lock_path):
            os.unlink(self.lock_path)


def atomic_write_text(file_path, content):
    directory = os.path.dirname(file_path)
    os.makedirs(directory, exist_ok=True)
    fd, temp_path = tempfile.mkstemp(prefix='.presetgen-', suffix='.tmp', dir=directory)
    try:
        with os.fdopen(fd, 'w', encoding='utf-8', newline='\n') as f:
            f.write(content)
        os.replace(temp_path, file_path)
    finally:
        if os.path.exists(temp_path):
            os.unlink(temp_path)


def atomic_copy_file(source_path, dest_path):
    directory = os.path.dirname(dest_path)
    os.makedirs(directory, exist_ok=True)
    fd, temp_path = tempfile.mkstemp(prefix='.presetgen-', suffix='.tmp', dir=directory)
    os.close(fd)
    try:
        shutil.copy2(source_path, temp_path)
        os.replace(temp_path, dest_path)
    finally:
        if os.path.exists(temp_path):
            os.unlink(temp_path)


def normalize_shader_ref(shader_ref):
    return os.path.normpath(shader_ref).replace('\\', '/')


def is_menu_shader_reference(shader_ref):
    return normalize_shader_ref(shader_ref).lower().startswith('menus/')


def sanitize_menu_owner_token(owner_name):
    token = MENU_NAME_TOKEN_PATTERN.sub('-', owner_name.strip().lower()).strip('-')
    return token or 'preset'


def build_generated_menu_shader_content(menu_shader_output_path, include_files):
    menu_dir = os.path.dirname(menu_shader_output_path)
    lines = ['#version 450', '// generated by presetgen']
    for include_path in include_files:
        rel_include = os.path.relpath(include_path, menu_dir).replace('\\', '/')
        lines.append(f'#include "{rel_include}"')
    lines.append(f'#include "{MENU_BASE_SHADER}"')
    return '\n'.join(lines) + '\n'


def compute_menu_signature(include_files, shader_root_abs, shader_ext):
    normalized_includes = []
    for include_path in sorted(include_files, key=lambda p: os.path.normcase(p)):
        rel_include = os.path.relpath(include_path, shader_root_abs).replace('\\', '/').lower()
        normalized_includes.append(rel_include)
    payload = {
        'menu_base': f"{os.path.splitext(MENU_BASE_SHADER)[0]}{shader_ext.lower()}",
        'includes': normalized_includes,
    }
    payload_json = json.dumps(payload, sort_keys=True, separators=(',', ':'))
    return hashlib.sha256(payload_json.encode('utf-8')).hexdigest()


def load_menu_manifest(manifest_path):
    if not os.path.exists(manifest_path):
        return {'version': 1, 'entries': {}}
    with open(manifest_path, 'r', encoding='utf-8') as f:
        data = json.load(f)
    if not isinstance(data, dict):
        return {'version': 1, 'entries': {}}
    entries = data.get('entries')
    if not isinstance(entries, dict):
        entries = {}
    return {'version': 1, 'entries': entries}


def parse_includes_recursive(file_path, visited, include_set):
    normalized = os.path.normcase(os.path.normpath(file_path))
    if normalized in visited:
        return
    if not os.path.exists(file_path):
        raise ValueError(f"Include source file not found: {file_path}")
    visited.add(normalized)

    with open(file_path, 'r', encoding='utf-8') as f:
        for line in f:
            match = INCLUDE_PATTERN.match(line)
            if not match:
                continue
            include_path = match.group(1)
            resolved = os.path.normpath(os.path.join(os.path.dirname(file_path), include_path))
            include_set.add(resolved)
            parse_includes_recursive(resolved, visited, include_set)


def find_parameter_includes(shader_file_paths, parameter_root_abs):
    parameter_root_normalized = os.path.normcase(os.path.normpath(parameter_root_abs))
    all_includes = set()
    visited = set()
    for shader_path in shader_file_paths:
        parse_includes_recursive(shader_path, visited, all_includes)

    parameter_includes = []
    for include_path in all_includes:
        include_normalized = os.path.normcase(os.path.normpath(include_path))
        if include_normalized == parameter_root_normalized or include_normalized.startswith(parameter_root_normalized + os.sep):
            parameter_includes.append(os.path.normpath(include_path))
    return sorted(parameter_includes, key=lambda p: p.lower())


def write_generated_menu_shader(menu_shader_output_path, include_files):
    content = build_generated_menu_shader_content(menu_shader_output_path, include_files)
    if os.path.exists(menu_shader_output_path):
        with open(menu_shader_output_path, 'r', encoding='utf-8') as f:
            existing = f.read()
        if existing == content:
            return False
    atomic_write_text(menu_shader_output_path, content)
    return True


def generate_menu_shaders(pipeline_objs, shader_root_abs, parameter_root_abs, shader_ext, preset_owner_name, vprint):
    shader_sources = []
    for pipeline in pipeline_objs:
        shaders = pipeline.data.get('shaders', {})
        for shader_file in shaders.values():
            if is_menu_shader_reference(shader_file):
                continue
            source_shader = os.path.normpath(os.path.join(shader_root_abs, shader_file))
            source_shader = ensure_shader_file_extension(source_shader, shader_ext)
            if not os.path.exists(source_shader):
                print(
                    f"Warning: skipping missing shader while building menu includes: {source_shader}",
                    file=sys.stderr,
                )
                continue
            shader_sources.append(source_shader)

    if not os.path.isdir(parameter_root_abs):
        raise ValueError(f"Menu parameter root does not exist: {parameter_root_abs}")

    parameter_includes = find_parameter_includes(shader_sources, parameter_root_abs)
    menu_signature = compute_menu_signature(parameter_includes, shader_root_abs, shader_ext)
    owner_token = sanitize_menu_owner_token(preset_owner_name)
    menu_dir_abs = os.path.join(shader_root_abs, 'menus')
    manifest_path = os.path.join(menu_dir_abs, MENU_MANIFEST_FILENAME)
    lock_path = manifest_path + '.lock'

    with ExclusiveFileLock(lock_path):
        manifest = load_menu_manifest(manifest_path)
        manifest_entries = manifest['entries']
        resolved_shader = manifest_entries.get(menu_signature)
        if not isinstance(resolved_shader, str) or not resolved_shader.strip():
            resolved_shader = f"menus/menu-{owner_token}-{menu_signature[:16]}{shader_ext}"
            resolved_shader = normalize_shader_ref(resolved_shader)
            manifest_entries[menu_signature] = resolved_shader
            atomic_write_text(manifest_path, json.dumps(manifest, indent=2, sort_keys=True) + '\n')

        output_shader = os.path.normpath(os.path.join(shader_root_abs, resolved_shader))
        changed = write_generated_menu_shader(output_shader, parameter_includes)
        if changed:
            vprint(f"Generated menu shader: {output_shader}")
        else:
            vprint(f"Reused menu shader: {output_shader}")

    resolved_shader_with_ext = normalize_shader_ref(resolved_shader)
    return {
        'with_ext': resolved_shader_with_ext,
        'without_ext': normalize_shader_ref(os.path.splitext(resolved_shader_with_ext)[0]),
    }


def copy_shader_tree(source_shader_root, output_shader_root, vprint):
    if not os.path.isdir(source_shader_root):
        raise ValueError(f"Shader root directory does not exist: {source_shader_root}")
    source_real = os.path.normcase(os.path.realpath(source_shader_root))
    output_real = os.path.normcase(os.path.realpath(output_shader_root))
    if output_real == source_real or output_real.startswith(source_real + os.sep):
        raise ValueError(
            f"Packaged shader output '{output_shader_root}' must not be inside shader root '{source_shader_root}'"
        )
    os.makedirs(output_shader_root, exist_ok=True)
    lock_path = os.path.join(output_shader_root, '.shader-copy.lock')
    with ExclusiveFileLock(lock_path):
        vprint(f"Synchronizing shaders to package output: {output_shader_root}")
        for source_dir, _, files in os.walk(source_shader_root):
            rel_dir = os.path.relpath(source_dir, source_shader_root)
            dest_dir = output_shader_root if rel_dir == '.' else os.path.join(output_shader_root, rel_dir)
            os.makedirs(dest_dir, exist_ok=True)
            for filename in files:
                source_file = os.path.join(source_dir, filename)
                dest_file = os.path.join(dest_dir, filename)
                should_copy = True
                if os.path.exists(dest_file):
                    source_stat = os.stat(source_file)
                    dest_stat = os.stat(dest_file)
                    should_copy = (
                        source_stat.st_size != dest_stat.st_size or
                        source_stat.st_mtime_ns != dest_stat.st_mtime_ns
                    )
                if should_copy:
                    atomic_copy_file(source_file, dest_file)

def main():
    parser = argparse.ArgumentParser(description="Generate preset output file.")
    parser.add_argument('-i', '--input', required=True, help='Input preset JSON file')
    parser.add_argument('-o', '--output', required=True, help='Output directory for generated preset')
    parser.add_argument('--shader-ext', default='.slang', help='Shader file extension to use (default: .slang)')
    parser.add_argument(
        '-c',
        '--config',
        required=True,
        help='Path to presetgen config JSON (must define root_path, pipeline_root, parameter_root)',
    )
    parser.add_argument('-v', '--verbose', action='store_true', help='Enable verbose output')
    args = parser.parse_args()

    def vprint(*a, **k):
        if args.verbose:
            print(*a, **k)

    vprint(f"Loading Preset: {args.input}")
    preset = Preset(args.input)
    preset_data = preset.data
    vprint("Preset loaded:", json.dumps(preset_data, indent=2))

    config = load_global_config(args.config)
    output_dir = os.path.normpath(args.output)
    presets_root = os.path.normpath(os.path.join(output_dir, 'presets'))
    packaged_shader_root = os.path.normpath(os.path.join(output_dir, 'shaders'))
    output_subdir = os.path.normpath(preset_data['type'])
    base_filename = os.path.splitext(os.path.normpath(preset_data['filename']))[0]
    output_filename = base_filename + '.slangp'
    output_path = os.path.normpath(os.path.join(presets_root, output_subdir))
    os.makedirs(output_path, exist_ok=True)
    output_file = os.path.normpath(os.path.join(output_path, output_filename))
    packaged_root_path = os.path.relpath(packaged_shader_root, output_path).replace('\\', '/')

    lines = []
    # Title comment
    lines.append(f"# {preset_data['title']}")
    lines.append('')
    # Description comment, wrapped
    lines.extend(wrap_comment(preset_data['description']))
    lines.append('')


    pipeline_root = config['pipeline_root_abs']
    parameter_root = config['parameter_root_abs']
    vprint(f"Pipeline root: {pipeline_root}")
    vprint(f"Parameter root: {parameter_root}")
    vprint(f"Source shader root: {config['shader_root_abs']}")
    vprint(f"Packaged shader root: {packaged_shader_root}")

    pipeline_objs = []
    for pipeline_file in preset_data.get('pipelines', []):
        pipeline_path = os.path.normpath(os.path.join(pipeline_root, pipeline_file))
        vprint(f"Loading Pipeline: {pipeline_path}")
        pipeline_obj = Pipeline(pipeline_path)
        if 'root_path' in pipeline_obj.data:
            raise ValueError(
                f"Pipeline '{pipeline_path}' contains deprecated 'root_path'. "
                "Move it to your config file's root_path."
            )
        vprint("Pipeline loaded:", json.dumps(pipeline_obj.data, indent=2))
        pipeline_objs.append(pipeline_obj)

    shader_count = 1
    for pipeline in pipeline_objs:
        for shader_file in pipeline.data.get('shaders', {}).values():
            if not is_menu_shader_reference(shader_file):
                shader_count += 1
    lines.append(f"shaders = {shader_count}")
    lines.append('')

    # Load all parameter sets
    param_objs = []
    for param_file in preset_data.get('parameter_sets', []):
        param_path = os.path.normpath(os.path.join(parameter_root, param_file))
        vprint(f"Loading Params: {param_path}")
        param_obj = Params(param_path)
        vprint("Params loaded:", json.dumps(param_obj.data, indent=2))
        param_objs.append(param_obj)

    # Assign unique numbers to shader stages across all pipelines
    shader_stage_map = {}  # (pipeline_idx, stage_key) -> unique_number
    shader_stage_counter = 0
    for pidx, pipeline in enumerate(pipeline_objs):
        shaders = pipeline.data.get('shaders', {})
        vprint(f"Pipeline {pidx} shaders: {json.dumps(shaders, indent=2)}")
        for stage_key, shader_file in shaders.items():
            if is_menu_shader_reference(shader_file):
                vprint(f"Skipping legacy menu shader stage {stage_key} in pipeline {pidx}: {shader_file}")
                continue
            shader_stage_map[(pidx, stage_key)] = shader_stage_counter
            vprint(f"Assigning shader stage {stage_key} in pipeline {pidx} to {shader_stage_counter}")
            shader_stage_counter += 1

    if args.verbose:
        print("Shader stage map:")
        for (pidx, stage_key), num in shader_stage_map.items():
            print(f"  Pipeline {pidx}, stage '{stage_key}': {num}")


    # --- Write shaders and options ---
    shader_ext = args.shader_ext if args.shader_ext.startswith('.') else '.' + args.shader_ext
    copy_shader_tree(config['shader_root_abs'], packaged_shader_root, vprint)
    generated_menu_shader = generate_menu_shaders(
        pipeline_objs=pipeline_objs,
        shader_root_abs=packaged_shader_root,
        parameter_root_abs=os.path.normpath(os.path.join(packaged_shader_root, 'menus', 'parameters')),
        shader_ext=shader_ext,
        preset_owner_name=base_filename,
        vprint=vprint,
    )

    lines.append(f"shader0 = {os.path.normpath(os.path.join(packaged_root_path, generated_menu_shader['with_ext'])).replace('\\', '/')}")
    lines.append("filter_linear0 = false")
    lines.append("scale_type0 = source")
    lines.append("scale0 = 1.0")
    lines.append("")

    for pidx, pipeline in enumerate(pipeline_objs):
        root_path = packaged_root_path
        shaders = pipeline.data.get('shaders', {})
        options = pipeline.data.get('options', {})
        for stage_key, shader_file in shaders.items():
            if is_menu_shader_reference(shader_file):
                vprint(f"Ignoring legacy menu shader stage '{stage_key}' from pipeline {pidx}: {shader_file}")
                continue
            idx = shader_stage_map[(pidx, stage_key)] + 1
            # Ensure shader_file ends with the extension while preserving forward-slash portability.
            shader_path = os.path.normpath(os.path.join(root_path, shader_file)).replace('\\', '/')
            shader_path = ensure_shader_file_extension(shader_path, shader_ext)
            lines.append(f"shader{idx} = {shader_path}")
            # Options for this shader stage
            opts = options.get(stage_key, {})

            # filter_linear: default false
            filter_linear_val = opts.get('filter_linear', False)
            lines.append(f"filter_linear{idx} = {str(filter_linear_val).lower()}")

            # mipmap_input: optional
            if 'mipmap_input' in opts:
                lines.append(f"mipmap_input{idx} = {str(opts['mipmap_input']).lower() if isinstance(opts['mipmap_input'], bool) else opts['mipmap_input']}")

            # wrap_mode: optional
            if 'wrap_mode' in opts:
                lines.append(f"wrap_mode{idx} = {opts['wrap_mode']}")

            # scale_type: default 'source', handle array
            scale_type_val = opts.get('scale_type', ['source'])
            if not isinstance(scale_type_val, list):
                scale_type_val = [scale_type_val]
            if len(scale_type_val) == 1:
                lines.append(f"scale_type{idx} = {scale_type_val[0]}")
            elif len(scale_type_val) == 2:
                lines.append(f"scale_type_x{idx} = {scale_type_val[0]}")
                lines.append(f"scale_type_y{idx} = {scale_type_val[1]}")

            # scale: handle array
            scale_written = False
            if 'scale' in opts:
                opt_val = opts['scale']
                if isinstance(opt_val, list):
                    if len(opt_val) == 1:
                        lines.append(f"scale{idx} = {opt_val[0]}")
                        scale_written = True
                    elif len(opt_val) == 2:
                        lines.append(f"scale_x{idx} = {opt_val[0]}")
                        lines.append(f"scale_y{idx} = {opt_val[1]}")
                        scale_written = True
                else:
                    lines.append(f"scale{idx} = {opt_val}")
                    scale_written = True
            # If no scale specified, add default
            if not scale_written:
                lines.append(f"scale{idx} = 1.0")

            # Other options
            for opt_key, opt_val in opts.items():
                if opt_key in ('filter_linear', 'scale_type', 'scale', 'mipmap_input', 'wrap_mode'):
                    continue
                lines.append(f"{opt_key}{idx} = {opt_val}")
            lines.append("")  # Separate each shader index group with a blank line

        # --- Write textures line ---
        textures = pipeline.data.get('textures', [])
        texture_options = pipeline.data.get('texture_options', {})
        for tex_name in texture_options:
            if tex_name not in textures:
                print(
                    f"Warning: texture '{tex_name}' exists in texture_options but is missing from textures array.",
                    file=sys.stderr,
                )
        if textures:
            textures_str = ';'.join(textures)
            lines.append(f'textures = "{textures_str}"')

        # --- Write texture_options lines ---
        for tex_name, tex_opts in texture_options.items():
            source_root_path = tex_opts.get('source_root_path')
            source = tex_opts.get('source')
            if source is not None:
                texture_source = os.path.normpath(os.path.join(source_root_path, source)) if source_root_path else source
                lines.append(f"{tex_name} = {texture_source}")
            for sub_key, sub_val in tex_opts.items():
                # Write linear, mipmap, mipmap_input, wrap_mode, and any other subproperty
                if sub_key in ('source_root_path', 'source'):
                    continue
                if sub_key in ('linear', 'mipmap', 'mipmap_input'):
                    lines.append(f"{tex_name}_{sub_key} = {str(sub_val).lower() if isinstance(sub_val, bool) else sub_val}")
                elif sub_key == 'wrap_mode':
                    lines.append(f"{tex_name}_wrap_mode = {sub_val}")
                else:
                    lines.append(f"{tex_name}_{sub_key} = {sub_val}")
        if textures or texture_options:
            lines.append("")

    # --- Write pipeline parameters (from each pipeline's parameters object) ---
    for pipeline in pipeline_objs:
        pipeline_params = pipeline.data.get('parameters', {})
        for k, v in pipeline_params.items():
            lines.append(f"{k} = {v}")
    if pipeline_objs:
        lines.append("")

    # --- Write parameters from parameter set JSON files ---
    for param_obj in param_objs:
        params = param_obj.data.get('parameters', {})
        rootpath = param_obj.data.get('rootpath') or param_obj.data.get('root_path', '')
        for k, v in params.items():
            # Only prepend rootpath for string values that look like file paths
            if isinstance(v, str) and rootpath:
                # Don't prepend if v is already an absolute path or contains a protocol
                if not (os.path.isabs(v) or v.startswith('..') or v.startswith('./') or ':' in v):
                    v = os.path.normpath(os.path.join(rootpath, v))
            lines.append(f"{k} = {v}")
    lines.append("")

    # Remove multiple blank lines
    pretty_lines = []
    last_blank = False
    for line in lines:
        if line.strip() == "":
            if not last_blank:
                pretty_lines.append("")
            last_blank = True
        else:
            pretty_lines.append(line)
            last_blank = False

    with open(output_file, 'w', encoding='utf-8') as f:
        f.write('\n'.join(pretty_lines))

    print(f"Generated: {output_file}")

if __name__ == "__main__":
    main()
